import {test,expect} from "@playwright/test";
import {createHash,randomBytes} from "crypto";
test("connect account, close and read a day, then revoke access",async({page,request})=>{
  const client_id="https://chatgpt.com/oauth/client.json";
  const redirect_uri="https://chatgpt.com/connector_platform_oauth_redirect";
  const resource="https://yoon-coach.vercel.app/api/mcp";
  const code_verifier=randomBytes(32).toString("base64url");
  const params=new URLSearchParams({client_id,redirect_uri,resource,response_type:"code",scope:"journal",state:"test-state",
    code_challenge_method:"S256",code_challenge:createHash("sha256").update(code_verifier).digest("base64url")});
  const rpc=(name:string,args:object,token="")=>request.post("/api/mcp",{headers:{authorization:"Bearer "+token},data:{jsonrpc:"2.0",id:1,method:"tools/call",params:{name,arguments:args}}});
  expect((await rpc("list_records",{})).status()).toBe(401);
  expect((await request.get("/.well-known/oauth-protected-resource/api/mcp")).ok()).toBeTruthy();
  await page.goto("/connect/chatgpt?"+params);
  await page.getByRole("button",{name:"회원가입",exact:true}).click();
  await page.getByLabel("이메일").fill("mcp-flow@example.invalid");
  await page.getByLabel("비밀번호").fill("only-for-local-test");
  await page.getByRole("button",{name:"계정 만들기"}).click();
  await page.route(redirect_uri+"**",route=>route.fulfill({body:"Connected"}));
  await page.getByRole("button",{name:"연결 허용"}).click();
  await page.waitForURL(redirect_uri+"**");
  const code=new URL(page.url()).searchParams.get("code")!;
  const form={client_id,redirect_uri,resource,grant_type:"authorization_code",code_verifier,code};
  const exchange=await request.post("/api/gpt-token",{form});
  expect(exchange.status()).toBe(200);
  const token=(await exchange.json()).access_token;
  expect((await request.post("/api/gpt-token",{form})).status()).toBe(400);
  const line="식단마감|날짜=2026-11-24|칼로리=2100|탄수=250|단백질=150|지방=55|목표칼로리=미상|목표탄수=미상|목표단백질=미상|목표지방=미상";
  const call=async(name:string,args:object)=>JSON.parse((await (await rpc(name,args,token)).json()).result.content[0].text);
  expect((await call("close_nutrition",{line})).saved).toBe(true);
  expect((await call("close_nutrition",{line})).saved).toBe(true);
  expect((await call("close_nutrition",{line:line.replace("2100","2300")})).saved).toBe(false);
  const records=await call("list_records",{from:"2026-11-24",to:"2026-11-24"});
  expect(records.nutrition).toHaveLength(1);
  expect(records.nutrition[0].calories).toBe(2100);
  expect((await call("get_workout_day",{date:"2026-09-06"})).legacyParts).toEqual([]);
  await page.goto("/auth");
  const revoked=await page.evaluate(async()=> (await fetch("/api/gpt-link",{method:"DELETE",headers:{"x-yooncoach-action":"disconnect"}})).status);
  expect(revoked).toBe(200);
  expect((await rpc("list_records",{},token)).status()).toBe(401);
});
